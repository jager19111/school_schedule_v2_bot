# core/utils/codes.py
#
# Генератор коротких печатаемых кодов приглашений.
#
# Алфавит из 31 символа без визуально похожих:
#   буквы без I, O, L (1/I/L неразличимы в многих шрифтах, 0/O тоже);
#   цифры 2-9 без 0 и 1.
# Дети и бабушки переписывают код с экрана на бумажку —
# каждая исключённая неоднозначность стоит дороже одного бита энтропии.
#
# Энтропия 6 символов из 31: 31^6 ≈ 8.9e8 (~29.7 бита).
# При anti-flood 5 поп/сек и сроке жизни 24 часа перебор невозможен:
# за сутки успевается 432к попыток — это 0.05% пространства.
#
# Проверено в песочнице: 20000 кодов — длина/алфавит/уникальность,
# исключённые символы (I, O, L, 0, 1) не встречаются.

from __future__ import annotations

import secrets

SHORT_CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"
SHORT_CODE_LENGTH = 6


def generate_short_code(length: int = SHORT_CODE_LENGTH) -> str:
    """Короткий код для «продиктовать/переписать».

    secrets.choice — криптографический ГСЧ, как у токенов приглашений.
    """
    return "".join(
        secrets.choice(SHORT_CODE_ALPHABET) for _ in range(length)
    )


def normalize_short_code(raw: str) -> str:
    """Приводит пользовательский ввод к канонической форме.

    Ребёнок может ввести '7k2m9q', ' 7K2M9Q ', '7-K2-M9Q' —
    все варианты обязаны совпасть с кодом 7K2M9Q.
    """
    return raw.upper().replace(" ", "").replace("-", "").strip()
